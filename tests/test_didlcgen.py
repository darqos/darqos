# Dispatch

def dispatch(driver, data: bytes, handles: typing.Sequence[int] = ()) -> tuple[str, bytes, str]:
    status, reply, note = driver("dispatch", data.hex(), *(f"{h:x}" for h in handles)).rsplit(" ", 2)
    return status, bytes.fromhex(reply) if reply != "-" else b"", note


def error_reply(data: bytes) -> tuple[int, int, int]:
    reply = dipc.ErrorReply()
    reply.decode(data)
    return reply.txid, reply.METHOD, reply.code


def test_dispatch(driver, generated):
    m = generated
    data, handles = m.ScalarsRequest(3, f=True, p=0x99).encode()
    status, reply, _ = dispatch(driver, data, handles)
    assert status == "OK" and decoded(m.ScalarsResponse, reply) == m.ScalarsResponse(3, True)

    status, reply, _ = dispatch(driver, m.StringsRequest(4, "ab", b"", "cd").encode()[0])
    assert decoded(m.StringsResponse, reply) == m.StringsResponse(4, "abcd")

    # One-way: no reply.
    assert dispatch(driver, m.Note(0, "noted").encode()[0]) == ("OK", b"", "noted")


def test_dispatch_errors(driver, generated):
    m = generated
    # Not implemented, a handler's error, an unknown method, and a bad request.
    assert error_reply(dispatch(driver, m.NestedRequest(5).encode()[0])[1]) == (5, 3, dipc.ErrorCode.NOT_IMPLEMENTED)
    data, handles = m.ScalarsRequest(6, a=99).encode()
    assert error_reply(dispatch(driver, data, handles)[1]) == (6, 1, dipc.ErrorCode.INTERNAL_ERROR)
    assert dispatch(driver, struct.pack("<IHH", 7, 0, 42))[0] == "wrong method"
    assert error_reply(dispatch(driver, struct.pack("<IHH", 7, 0, 42))[1]) == (7, 42, dipc.ErrorCode.UNKNOWN_METHOD)
    bad = corrupt(m.StringsRequest(8, "abc", b"", "").encode()[0], 33, b"\xff")
    status, reply, _ = dispatch(driver, bad)
    assert status == "string value is not valid UTF-8"
    assert error_reply(reply) == (8, 2, dipc.ErrorCode.BAD_MESSAGE)

    # A one-way message gets no error reply.
    assert dispatch(driver, corrupt(m.Note(0, "x").encode()[0], 16, b"\xff")) == (
        "string value is not valid UTF-8", b"", "-")
