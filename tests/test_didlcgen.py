class Driver:
    def __init__(self, program: pathlib.Path):
        self.process = subprocess.Popen([program], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True)

    def __call__(self, *words: str) -> str:
        assert self.process.stdin is not None and self.process.stdout is not None
        self.process.stdin.write(" ".join(words) + "\n")
        self.process.stdin.flush()
        return self.process.stdout.readline().strip()

    def built(self, *words: str) -> tuple[bytes, list[int]]:
        """A message the driver built, and its handles."""
        out = self(*words)
        assert not out.startswith("error"), out
        hex_data, *handles = out.split()
        return bytes.fromhex(hex_data), [int(h, 16) for h in handles]

    def close(self):
        self.process.communicate()


