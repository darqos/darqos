# C builds, Python decodes

def test_c_builds_scalars(driver, generated):
    data, handles = driver.built("scalars")
    assert decoded(generated.ScalarsRequest, data, handles) == scalars(generated)
    assert (data, handles) == scalars(generated).encode()


@pytest.mark.parametrize("s, o, t", [
    ("plain", b"raw", "naïve 😀"),
    ("", b"", ""),
    ("12345678", b"12345678", "1234567"),
])
def test_c_builds_strings(driver, generated, s, o, t):
    args = (hexed(s.encode()), hexed(o), hexed(t.encode()))
    expected = generated.StringsRequest(5, s, o, t)
    data, _ = driver.built("strings", *args)
    assert data == expected.encode()[0]

    # Set in another order, the values are too: it still decodes.
    data, _ = driver.built("strings-reversed", *args)
    assert decoded(generated.StringsRequest, data) == expected


def test_c_builds_nested(driver, generated):
    data, handles = driver.built("nested")
    assert handles == [0x10]
