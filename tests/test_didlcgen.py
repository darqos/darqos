def compile_ir(source: str) -> dict:
    return didlc.compile_ir(didlc.Parser(didlc.lex(textwrap.dedent(source))).parse())


def generate(source: str) -> tuple[str, str]:
    return didlcgen.Generator(compile_ir(source), "test.dir").generate()


def generate_error(source: str) -> str:
    with pytest.raises(didlcgen.GenError) as info:
        generate(source)
    return str(info.value)


