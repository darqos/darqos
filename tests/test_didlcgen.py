def corrupt(data: bytes, offset: int, value: bytes) -> bytes:
    changed = bytearray(data)
    changed[offset:offset + len(value)] = value
    return bytes(changed)


def string_cases(m) -> list[tuple[str, str, bytes]]:
    """(name, error, message) for bad Strings requests: s's descriptor is
    at 8, o's at 16, t's at 24; their values at 32, 40, 48."""
    good = m.StringsRequest(0, "abc", b"de", "fgh").encode()[0]
    return [
        ("misaligned value", "value not 8-byte aligned", corrupt(good, 8, struct.pack("<I", 33))),
        ("value before data", "value out of range", corrupt(good, 8, struct.pack("<I", 24))),
        ("value past end", "value out of range", corrupt(good, 8, struct.pack("<II", 48, 9))),
        ("overlap", "value overlaps another", corrupt(good, 24, struct.pack("<I", 32))),
        ("no NUL", "string value isn't followed by a NUL", corrupt(good, 35, b"x")),
        ("NUL inside", "string value contains a NUL", corrupt(good, 33, b"\0")),
        ("bad UTF-8", "string value is not valid UTF-8", corrupt(good, 33, b"\xff")),
        ("short", "too short for the message", good[:31]),
        ("wrong method", "wrong method", corrupt(good, 6, struct.pack("<H", 1))),
        ("wrong flags", "wrong flags", corrupt(good, 4, struct.pack("<H", 1))),
    ]


