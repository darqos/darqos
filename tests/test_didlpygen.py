def test_exports(fs):
    assert sorted(fs.__all__) == sorted([
        "Entry", "FileAttributes", "FileServer", "Foo",
        "GetAttributesRequest", "GetAttributesResponse",
        "ListRequest", "ListResponse", "Named", "Ping",
        "RenameRequest", "RenameResponse"])
    for name in fs.__all__:
        assert hasattr(fs, name)


def test_no_boilerplate(fs):
    # The common classes come from darq.dipc, not the generated module.
    assert fs.Message is dipc.Message
    assert fs.Record is dipc.Record
    assert issubclass(fs.Ping, dipc.Message)
    assert issubclass(fs.FileAttributes, dipc.Record)
    for name in ("HEADER_FORMAT", "HEADER_LENGTH", "decode_method", "decode_txid"):
        assert not hasattr(fs, name)


def test_imports_only_what_is_used():
    assert generate("library t;\nprotocol P { 1: Ping(); }").splitlines()[4] == \
        "from darq.dipc import Message"
    text = generate("library t;\nstruct S { uint8 x; }")
    assert "from darq.dipc import Record" in text
    assert "import struct" not in text
    assert "MessageDecodingError" not in text


