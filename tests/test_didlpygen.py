def test_round_trip_primitives(fs):
    message = fs.Foo(7, 1, 2, -3, 1.5, 2.25, True, b"\x00\xffdata", 16385)
    assert round_trip(message) == message


def test_round_trip_nested_structs(fs):
    message = fs.ListResponse(8, fs.Entry(1, fs.FileAttributes(2 ** 64 - 1, 3, 4)), 255)
    decoded = round_trip(message)
    assert decoded == message
    assert decoded.first is not message.first


def test_round_trip_opaque_in_struct(fs):
    message = fs.RenameRequest(9, fs.Named(2, b"old"), b"new")
    assert round_trip(message) == message


def test_round_trip_empty(fs):
    assert round_trip(fs.Ping(4)) == fs.Ping(4)


def test_decode_ignores_trailing_bytes(fs):
    message = fs.GetAttributesRequest(1, 2)
    decoded = fs.GetAttributesRequest()
    decoded.decode(message.encode() + b"extra")
    assert decoded == message


