def generate_error(source: str) -> str:
    with pytest.raises(didlpygen.GenError) as info:
        generate(source)
    return str(info.value)


def test_keyword_field_name():
    assert "not a valid Python identifier" in generate_error(
        "library t;\nprotocol P { 1: M(uint8 class); }")


def test_dotted_struct_name():
    assert "not a valid Python identifier" in generate_error(
        "library t;\nstruct a.b { uint8 x; }")


def test_class_name_collision_between_protocols():
    error = generate_error("library t;\nprotocol A { 1: X(); }\nprotocol B { 1: X(); }")
    assert "Class name 'X' of B.X request is already used" in error


def test_class_name_collision_with_struct():
    error = generate_error("library t;\nstruct MRequest {}\nprotocol P { 1: M() -> (); }")
    assert "'MRequest'" in error


def test_reserved_name():
    assert "reserved" in generate_error("library t;\nstruct Message {}")


