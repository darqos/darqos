def run_main(monkeypatch, *argv):
    monkeypatch.setattr(sys, "argv", ["didlpygen", *argv])
    return didlpygen.main()


def write_ir(tmp_path: pathlib.Path) -> pathlib.Path:
    path = tmp_path / "fs.dir"
    path.write_text(json.dumps(compile_ir(SOURCE)))
    return path


def test_main_default_output(tmp_path, monkeypatch):
    assert run_main(monkeypatch, str(write_ir(tmp_path))) == 0
    text = (tmp_path / "storage_filesystem.py").read_text()
