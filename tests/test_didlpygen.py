BIN = pathlib.Path(__file__).parent.parent / "bin"


def load_script(name: str):
    """Import a script from bin/ as a module (it has no .py extension)."""
    loader = importlib.machinery.SourceFileLoader(name, str(BIN / name))
    spec = importlib.util.spec_from_loader(name, loader)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


didlc = load_script("didlc")
didlpygen = load_script("didlpygen")


SOURCE = """
    library storage.filesystem;

    struct FileAttributes {
        uint64 size;
        uint32 permissions;
        uint32 owner_id;
    }

    struct Named {
        uint8 kind;
        opaque name;
    }

    struct Entry {
        uint16 flags;
        FileAttributes attr;
    }

    protocol FileServer {
        1: GetAttributes(uint64 fd) -> (FileAttributes attr, uint32 status);
        2: Foo(uint8 a, uint16 b, int8 c, real32 d, real64 e, bool f, opaque g, port h);
        3: Ping();
        4: Rename(Named old, opaque new_name) -> ();
        5: List() -> (Entry first, uint8 count);
    }
    """


def compile_ir(source: str) -> dict:
    return didlc.compile_ir(didlc.Parser(didlc.lex(textwrap.dedent(source))).parse())


def generate(source: str) -> str:
    return didlpygen.Generator(compile_ir(source), "test.dir").generate()


def import_module(text: str, tmp_path: pathlib.Path, name: str = "generated"):
    path = tmp_path / f"{name}.py"
    path.write_text(text)
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture
def fs(tmp_path):
    """The generated module for SOURCE."""
    return import_module(generate(SOURCE), tmp_path)


def round_trip(message):
    decoded = type(message)()
    decoded.decode(message.encode())
    return decoded


